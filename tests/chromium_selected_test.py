def sfnt_fixture(source,path,family,changed,removed=()):
    data=source.read_bytes();count=struct.unpack_from('>H',data,4)[0];tables={}
    for i in range(count):
        tag,_,offset,size=struct.unpack_from('>4sIII',data,12+16*i);tables[tag]=data[offset:offset+size]
    names=tables[b'name'];version,count,offset=struct.unpack_from('>HHH',names);assert version==0
    records=b'';strings=b''
    for i in range(count):
        platform,encoding,language,name,length,start=struct.unpack_from('>6H',names,6+12*i)
        value=names[offset+start:offset+start+length]
        if name in (1,4,6,16):value=family.encode('utf-16-be' if platform in (0,3) else 'ascii')
        records+=struct.pack('>6H',platform,encoding,language,name,len(value),len(strings));strings+=value
    tables[b'name']=struct.pack('>HHH',0,count,6+12*count)+records+strings
    tables.update(changed);tables.pop(b'DSIG',None)
    for tag in removed:tables.pop(tag,None)
    tables[b'head']=tables[b'head'][:8]+b'\0'*4+tables[b'head'][12:]
    power=len(tables).bit_length()-1
    directory=struct.pack('>4sHHHH',data[:4],len(tables),16*(1<<power),power,16*len(tables)-16*(1<<power))
    body=bytearray();head=None
    for tag,contents in sorted(tables.items()):
        padded=contents+b'\0'*((-len(contents))%4);offset=12+16*len(tables)+len(body)
        checksum=sum(struct.unpack(f'>{len(padded)//4}I',padded))&0xffffffff
        directory+=struct.pack('>4sIII',tag,checksum,offset,len(contents));body.extend(padded)
        if tag==b'head':head=offset
    output=bytearray(directory)+body;checksum=sum(struct.unpack(f'>{len(output)//4}I',output))&0xffffffff
    struct.pack_into('>I',output,head+8,(0xb1b0afba-checksum)&0xffffffff);path.write_bytes(output)
    return path


