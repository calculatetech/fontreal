def check_trace(case,fixture,oracles,ids,profile=None):
    transitions=[row for row in fixture['rows'] if row['owner']=='selected']
    targets=[row for row in fixture['rows'] if row['owner']=='selected-target']
    assert transitions and targets,'Selected renderer emitted no actual glyph transitions or target observations'
    counts={stage:fixture['observations'][stage]['selectedRasterCount'] for stage in STAGES}
    assert counts['empty']==0,'An empty stage rasterized a selected glyph'
    assert counts['repaint']==counts['prefix'] and counts['later-repaint']==counts['later'],'Repaint processed a cached image again'
    assert counts['matrix']==len(transitions),'Raster trace was incomplete at the final capture'
    if case.get('excluded'):
        assert counts['one']==counts['prefix']==0,'An excluded first face produced selected work'
    else:
        assert counts['one']==1 and transitions[0]['glyph']==ids[0]['m'] and transitions[0]['size']==15,'First actual drawn m was not the first single selected raster'
    prefix_rows=transitions[:counts['prefix']];later_rows=transitions[:counts['later']]
