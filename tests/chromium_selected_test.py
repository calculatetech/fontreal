def fixture_config(case,palette,files):
    background='#202124' if palette=='dark' else '#ffffff';foreground='#f1f3f4' if palette=='dark' else '#000000'
    fonts=[dict(file=str(files[0]),family=case['family'],local=case.get('local',False),variation=case.get('variation','normal'))]
    if case.get('excluded'):fonts.append(dict(file=str(files[1]),family='Noto Sans'))
    def cell(char,index,pixels=15,font=0,**extra):
        value=dict(id=f'{index}-{ord(char)}',char=char,font=font,pixels=pixels,x=24+(index%39)*27,y=80+(index//39)*36)
        value.update(extra);return value
    prefix=[cell(char,index) for index,char in enumerate('m8Wm8W')]
    if case.get('characters')=='m':prefix=[cell('m',index) for index in range(6)]
    later=prefix+[cell('g',6,font=1 if case.get('excluded') else 0)]
    matrix=[];characters=case.get('characters',''.join(map(chr,range(32,127))))
    for pixels in SIZES:
        for char in characters:matrix.append(cell(char,len(matrix),pixels))
    if case.get('excluded'):
        for char in 'm8Wg':matrix.append(cell(char,len(matrix),15,font=1))
    else:
        for phase in (.49,.51):matrix.append(cell('m',len(matrix),15,x=24+(len(matrix)%39)*27+phase))
        matrix.append(cell('W',len(matrix),15,stroke=1))
        matrix.append(cell('8',len(matrix),15,unhinted=True))
        matrix.append(cell('g',len(matrix),15,transform=[1,.1,.2,1,0,0],native_transform=True))
        matrix.append(cell('.',len(matrix),300,x=800,y=490,native_path=True))
        matrix.append(cell('g',len(matrix),17))
    return dict(width=1100,height=520,fonts=fonts,foreground=foreground,background=background,
                stages=dict(empty=[],one=prefix[:1],prefix=prefix,repaint=prefix,later=later,**{'later-repaint':later},matrix=matrix))


def capture_window(env,identity,destination,stage,background,collector,empty_primary=False):
    measurement=identity['measurement'];assert measurement['dpr']==1 and measurement['fontLoaded'] and not measurement['contextLost']
    width,height=measurement['width'],measurement['height'];assert (width,height)==(1100,520)
    with Image.open(identity['capture']) as native:
        assert native.size==(width,height) and native.mode in ('RGB','RGBA')
        native_bg=native.getpixel((1090,500))[:3]
        marker=native.getpixel((16,16))[:3];control=native.getpixel((40,16))[:3]
        assert len({marker,control,native_bg})==3
        assert {pixel[:3] for pixel in native.crop((16,16,24,24)).getdata()}=={marker}
        assert sum(pixel[:3]==marker for pixel in native.getdata())==64
        assert {pixel[:3] for pixel in native.crop((40,16,58,34)).getdata()}=={control}
        native_info=dict(mode=native.mode,backgroundRGB=native_bg,markerRGB=marker,controlRGB=control,
                         iccProfileBytes=len(native.info.get('icc_profile',b'')))
    deadline=time.monotonic()+15
    while True:
        collector.check();root=masks.screenshot(env,destination/(stage+'-root.png'))
        points=[(i%root.width,i//root.width) for i,pixel in enumerate(root.getdata()) if pixel==(17,91,143)]
        if len(points)==64:
            x=min(p[0] for p in points)-16;y=min(p[1] for p in points)-16
            if 0<=x and 0<=y and x+width<=root.width and y+height<=root.height:
                crop=root.crop((x,y,x+width,y+height))
                controls=set(crop.crop((16,16,24,24)).getdata())=={(17,91,143)} and set(crop.crop((40,16,58,34)).getdata())=={(53,89,131)} and crop.getpixel((1090,500))==background
                painted=True
                for cell in measurement['cells']:
                    if cell['char']==' ':continue
                    if empty_primary and cell['font']==0:continue
                    metrics=cell['metrics']
                    assert all(math.isfinite(value) for value in metrics.values()),'Canvas text metrics are not finite'
                    a,b,c,d,tx,ty=cell.get('transform',[1,0,0,1,0,0])
                    corners=[(a*x+c*y+tx,b*x+d*y+ty) for x in (cell['x']-metrics['left'],cell['x']+metrics['right'])
                             for y in (cell['y']-metrics['ascent'],cell['y']+metrics['descent'])]
                    padding=1+cell.get('stroke',0)
                    box=(math.floor(min(x for x,y in corners))-padding,math.floor(min(y for x,y in corners))-padding,
                         math.ceil(max(x for x,y in corners))+padding,math.ceil(max(y for x,y in corners))+padding)
                    assert 0<=box[0]<box[2]<=width and 0<=box[1]<box[3]<=height,'Actual glyph geometry lies outside the fixture'
                    if cell.get('native_path'):
                        assert 800<=box[0]<box[2]<=950 and 420<=box[1]<box[3]<=510,'Native path control overlaps another actor'
                    if not any(pixel!=background for pixel in crop.crop(box).getdata()):painted=False;break
                if controls and painted:
                    crop.save(destination/(stage+'-window.png'));return dict(origin=[x,y],width=width,height=height,cellsPainted=len(measurement['cells']),native=native_info)
        assert time.monotonic()<deadline,'Selected real OS fixture did not paint its controls'
        time.sleep(.1)


